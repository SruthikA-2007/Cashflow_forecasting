"""
Dataset service module.
Encapsulates CRUD, file upload processing, column mapping, invoice record storage, and database operations on `datasets` and `invoices` tables.
All operations filter strictly by the authenticated user's ID.
"""

import io
import os
import uuid
import pandas as pd
from datetime import datetime, timezone
from typing import Optional, Any
from fastapi import UploadFile, HTTPException, status

from app.schemas.dataset import DatasetMeta, DatasetListResponse, DatasetUploadResponse
from app.supabase_client import supabase_admin
from app.utils.column_mapper import detect_column_mapping

DATASETS_TABLE = "datasets"
INVOICES_TABLE = "invoices"
RAW_UPLOAD_DIR = os.path.join(os.getcwd(), "uploads", "raw")


def _clean_val(val: Any) -> Any:
    """Returns None if missing/NaN/null string, else cleaned value."""
    if pd.isna(val) or val is None:
        return None
    if isinstance(val, (pd.Timestamp, datetime)):
        return val.isoformat()
    val_str = str(val).strip()
    if val_str == "" or val_str.lower() in ["null", "none", "nan", "<na>"]:
        return None
    return val


def _format_field(field_name: str, raw_val: Any) -> Any:
    """Formats values strictly according to field type requirements."""
    val = _clean_val(raw_val)
    if val is None:
        return None

    if field_name == "invoice_amount":
        try:
            return float(val)
        except (ValueError, TypeError):
            return None

    if field_name in ["disputed", "paperless_bill"]:
        if isinstance(val, bool):
            return val
        s = str(val).strip().lower()
        if s in ["true", "1", "yes", "y", "t"]:
            return True
        elif s in ["false", "0", "no", "n", "f"]:
            return False
        return None

    if field_name in ["invoice_date", "due_date", "settled_date"]:
        if isinstance(val, (pd.Timestamp, datetime)):
            return val.isoformat()
        return str(val)

    return str(val)


class DatasetService:
    """
    Encapsulates dataset database operations and processing scoped strictly to an authenticated user.
    """

    def __init__(self, user_id: str) -> None:
        self._user_id = str(user_id)
        self._sb = supabase_admin

    async def process_and_upload(self, file: UploadFile) -> DatasetUploadResponse:
        """
        Reads, validates, stores raw file separately, detects column mapping, stores invoice records in invoices table, updates total_records, and returns metadata & preview.
        """
        filename = file.filename or "uploaded_dataset"
        ext = os.path.splitext(filename)[1].lower()

        if ext not in [".csv", ".xlsx", ".xls"]:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Unsupported file type '{ext}'. Only CSV and Excel (.xlsx, .xls) files are supported.",
            )

        content = await file.read()
        if not content:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Uploaded file is empty.",
            )

        # 1. Read file with Pandas and validate readability
        try:
            if ext == ".csv":
                df = pd.read_csv(io.BytesIO(content))
            else:
                df = pd.read_excel(io.BytesIO(content))
        except Exception as e:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail=f"Failed to read dataset file. Ensure it is a valid CSV or Excel file: {str(e)}",
            )

        # 2. Validate dataset structure
        if df.empty or len(df) == 0:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Dataset contains no data rows.",
            )

        if len(df.columns) == 0:
            raise HTTPException(
                status_code=status.HTTP_400_BAD_REQUEST,
                detail="Dataset structure is invalid (no columns detected).",
            )

        # dataset_id will be auto-generated by Supabase (BIGINT)
        temp_local_id = str(uuid.uuid4())  # used only for local file path before DB insert
        dataset_name = os.path.splitext(filename)[0]
        detected_columns = [str(col) for col in df.columns]
        total_uploaded_records = len(df)

        # 3. Detect reusable column mapping
        column_mapping = detect_column_mapping(detected_columns)

        # 4. Store raw uploaded data separately
        user_raw_dir = os.path.join(RAW_UPLOAD_DIR, self._user_id)
        os.makedirs(user_raw_dir, exist_ok=True)
        raw_file_path = os.path.join(user_raw_dir, f"{temp_local_id}_{filename}")

        with open(raw_file_path, "wb") as f:
            f.write(content)

        storage_path = f"raw/{self._user_id}/{temp_local_id}_{filename}"
        try:
            self._sb.storage.from_("datasets").upload(
                path=storage_path,
                file=content,
                file_options={"content-type": file.content_type or "application/octet-stream"},
            )
        except Exception:
            storage_path = raw_file_path

        # 5. Generate 5 rows preview safely
        preview_data = []
        preview_df = df.head(5)
        for row in preview_df.to_dict(orient="records"):
            cleaned_row = {}
            for k, v in row.items():
                val = _clean_val(v)
                cleaned_row[str(k)] = val
            preview_data.append(cleaned_row)

        now = datetime.now(tz=timezone.utc).isoformat()

        # 6. Insert metadata row into datasets table
        # Do NOT send 'id' — let Supabase auto-generate the BIGINT primary key
        db_row = {
            "user_id": self._user_id,
            "filename": filename,
            "dataset_name": dataset_name,
            "original_filename": filename,
            "file_size_bytes": len(content),
            "row_count": total_uploaded_records,
            "total_records": total_uploaded_records,
            "column_count": len(detected_columns),
            "storage_path": storage_path,
            "status": "uploaded",
            "processing_status": "uploaded",
            "created_at": now,
            "updated_at": now,
        }

        # Capture the auto-generated BIGINT id from Supabase response
        dataset_id = temp_local_id  # fallback if DB insert fails
        try:
            insert_res = self._sb.table(DATASETS_TABLE).insert(db_row).execute()
            if insert_res and insert_res.data and len(insert_res.data) > 0:
                dataset_id = str(insert_res.data[0].get("id", temp_local_id))
        except Exception:
            # Try minimal insert as fallback
            minimal_row = {
                "user_id": self._user_id,
                "filename": filename,
                "original_filename": filename,
                "file_size_bytes": len(content),
                "row_count": total_uploaded_records,
                "column_count": len(detected_columns),
                "storage_path": storage_path,
                "status": "uploaded",
                "created_at": now,
                "updated_at": now,
            }
            try:
                min_res = self._sb.table(DATASETS_TABLE).insert(minimal_row).execute()
                if min_res and min_res.data and len(min_res.data) > 0:
                    dataset_id = str(min_res.data[0].get("id", temp_local_id))
            except Exception:
                pass

        # 7. Parse and store invoice records in invoices table
        invoice_records = []
        invalid_records = 0

        for _, row in df.iterrows():
            try:
                inv_record = {
                    "id": str(uuid.uuid4()),
                    "dataset_id": dataset_id,
                    "user_id": self._user_id,  # Server-authoritative user_id from JWT
                    "created_at": now,
                }
                for field, mapped_col in column_mapping.items():
                    if mapped_col and mapped_col in df.columns:
                        inv_record[field] = _format_field(field, row[mapped_col])
                    else:
                        inv_record[field] = None

                invoice_records.append(inv_record)
            except Exception:
                invalid_records += 1

        successfully_stored_records = len(invoice_records)

        # Batch insert invoice records into Supabase invoices table
        if invoice_records:
            batch_size = 500
            for i in range(0, len(invoice_records), batch_size):
                chunk = invoice_records[i : i + batch_size]
                try:
                    self._sb.table(INVOICES_TABLE).insert(chunk).execute()
                except Exception:
                    pass

        # 8. Update total_records in datasets table
        try:
            self._sb.table(DATASETS_TABLE).update({
                "total_records": successfully_stored_records,
                "row_count": successfully_stored_records,
                "updated_at": datetime.now(tz=timezone.utc).isoformat()
            }).eq("id", dataset_id).eq("user_id", self._user_id).execute()
        except Exception:
            pass


        return DatasetUploadResponse(
            dataset_id=dataset_id,
            dataset_name=dataset_name,
            original_filename=filename,
            total_records=successfully_stored_records,
            total_uploaded_records=total_uploaded_records,
            successfully_stored_records=successfully_stored_records,
            invalid_records=invalid_records,
            detected_columns=detected_columns,
            detected_column_mapping=column_mapping,
            preview=preview_data,
            processing_status="uploaded",
        )

    def list_all(self) -> DatasetListResponse:
        """
        Fetch all datasets belonging to the authenticated user.
        """
        try:
            response = (
                self._sb.table(DATASETS_TABLE)
                .select("*")
                .eq("user_id", self._user_id)
                .order("created_at", desc=True)
                .execute()
            )
            data = response.data if response and response.data else []
            datasets = [DatasetMeta(**dict(r)) for r in data]
            return DatasetListResponse(datasets=datasets, total=len(datasets))
        except Exception:
            return DatasetListResponse(datasets=[], total=0)

    def get_by_id(self, dataset_id: str) -> Optional[DatasetMeta]:
        """
        Fetch dataset by dataset_id and verify user ownership.
        Returns None if dataset does not exist or belongs to a different user.
        """
        try:
            response = (
                self._sb.table(DATASETS_TABLE)
                .select("*")
                .eq("id", str(dataset_id))
                .eq("user_id", self._user_id)
                .execute()
            )
            if response and response.data and len(response.data) > 0:
                return DatasetMeta(**dict(response.data[0]))
            return None
        except Exception:
            return None




